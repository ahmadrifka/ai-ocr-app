CREATE SCHEMA IF NOT EXISTS public;

-- Reuse the existing Supabase table; create it on fresh installs.
CREATE TABLE IF NOT EXISTS public.accounts (
    account_number text,
    account_name text,
    bank_name text
);

ALTER TABLE public.accounts ENABLE ROW LEVEL SECURITY;

CREATE TABLE public."transaction" (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    transaction_date timestamptz,
    transaction_id varchar(255),
    dedupe_key varchar(64),
    description text NOT NULL DEFAULT '',
    category varchar(100) NOT NULL DEFAULT 'Uncategorized',
    transaction_type varchar(100) NOT NULL DEFAULT 'EXPENSES',
    beneficiary_bank varchar(255),
    beneficiary_account_number varchar(100),
    benecifiacry_account_name varchar(255),
    source_bank varchar(255),
    source_account_number varchar(100),
    source_account_name varchar(255),
    amount numeric(18, 2),
    asset_path varchar(500) NOT NULL
);

CREATE UNIQUE INDEX transaction_dedupe_key_uq
    ON public."transaction" (dedupe_key)
    WHERE dedupe_key IS NOT NULL;

CREATE TABLE public.ocr_upload_job (
    upload_id uuid PRIMARY KEY,
    idempotency_key varchar(255) NOT NULL UNIQUE,
    asset_path varchar(500),
    content_type varchar(100) NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'DUPLICATE', 'FAILED')),
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    available_at timestamptz NOT NULL DEFAULT now(),
    lease_until timestamptz,
    transaction_record_id integer REFERENCES public."transaction" (id) ON DELETE SET NULL,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ocr_upload_job_pickup_idx
    ON public.ocr_upload_job (status, available_at);
CREATE INDEX ocr_upload_job_duplicate_cleanup_idx
    ON public.ocr_upload_job (status, asset_path);

ALTER TABLE public.ocr_upload_job ENABLE ROW LEVEL SECURITY;

CREATE INDEX transaction_category_idx ON public."transaction" (category);

ALTER TABLE public."transaction" ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.transaction_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at := pg_catalog.now();
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.transaction_set_updated_at() FROM PUBLIC;

CREATE TRIGGER transaction_set_updated_at
BEFORE UPDATE ON public."transaction"
FOR EACH ROW
EXECUTE FUNCTION public.transaction_set_updated_at();
