CREATE SCHEMA IF NOT EXISTS public;

CREATE TABLE public."transaction" (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    transaction_date timestamptz,
    description text NOT NULL DEFAULT '',
    category varchar(100) NOT NULL DEFAULT 'Uncategorized',
    transaction_type varchar(100) NOT NULL DEFAULT 'EXPENSES',
    beneficiary_bank varchar(255),
    beneficiary_account_number varchar(100),
    benecifiacry_account_name varchar(255),
    source_bank varchar(255),
    source_account_number varchar(100),
    source_account_name varchar(255),
    amount numeric(18, 2),
    asset_path varchar(500) NOT NULL
);

CREATE INDEX transaction_category_idx ON public."transaction" (category);

ALTER TABLE public."transaction" ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.transaction_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at := pg_catalog.now();
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.transaction_set_updated_at() FROM PUBLIC;

CREATE TRIGGER transaction_set_updated_at
BEFORE UPDATE ON public."transaction"
FOR EACH ROW
EXECUTE FUNCTION public.transaction_set_updated_at();
